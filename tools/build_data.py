#!/usr/bin/env python3
"""
Procedural Adventures - game data builder.

Parses Pride and Prejudice (public domain: places, people, quotable lines) into src/gen/data.js.

The creatures, their attacks and the type chart live in src/game/roster.js.

usage: python3 tools/build_data.py <dir-with-pride-and-prejudice.txt>
"""
import sys, os, re, json

SRC = sys.argv[1] if len(sys.argv) > 1 else 'source'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'gen', 'data.js')

# ---------------------------------------------------------------- Austen
pp = open(os.path.join(SRC, 'pride and prejudice.txt'), encoding='utf-8', errors='replace').read()
pp = pp.replace('\r', '')
st = pp.find('Chapter 1')
if st < 0:
    st = pp.find('CHAPTER I')
en = pp.find('END OF THE PROJECT GUTENBERG')
body = pp[st:en if en > 0 else len(pp)]
body = body.replace('“', '"').replace('”', '"').replace('’', "'").replace('‘', "'").replace('_', '')
flat = ' '.join(body.split())
flat2 = re.sub(r'\b(Mr|Mrs|Dr|St)\. ', r'\1~ ', flat)
sents = [x.replace('~', '.') for x in re.split(r'(?<=[\.\!\?])\s+(?=[A-Z"])', flat2)]
GOOD = re.compile(r"^[A-Za-z0-9 ,;:'\.\!\?\-]+$")
quotes = []
for s in sents:
    s = s.strip().strip('"').strip()
    if 35 <= len(s) <= 110 and GOOD.match(s) and not re.search(r'\b(Mr|Mrs|Miss|Lady|Sir|Colonel)\b\.?$', s):
        if s[0].isupper() and s[-1] in '.!?' and s.count('"') == 0:
            quotes.append(s)
# keep aphoristic lines (general truths) preferentially
APH = re.compile(r'\b(never|always|every|nothing|happiness|heart|mind|pride|vanity|prejudice|love|feeling|'
                 r'truth|nobody|everybody|world|life|pleasure|sense|folly|wisdom|good|character)\b', re.I)
aph = [q for q in quotes if APH.search(q) and not re.search(r'\b(she|he|her|him|his)\b', q[:12], re.I)]
print('quotes', len(quotes), 'aphorisms', len(aph))
words = re.findall(r"\b[A-Z][a-z]{3,}\b", flat)
freq = {}
for w in words:
    freq[w] = freq.get(w, 0) + 1
# hand-checked places and people present in the novel
PLACES = ['Longbourn', 'Netherfield', 'Meryton', 'Pemberley', 'Rosings', 'Hunsford', 'Lambton', 'Brighton',
          'Derbyshire', 'Hertfordshire', 'Kent', 'Gracechurch', 'Kympton', 'Oakham', 'Matlock', 'Chatsworth',
          'Dovedale', 'Blenheim', 'Kenilworth', 'Birmingham', 'Bakewell', 'Ramsgate', 'Barnet', 'Hatfield',
          'Epsom', 'Clapham', 'Stoke', 'Ashworth', 'Haye', 'Purvis', 'Lucas', 'Scarborough', 'Bromley',
          'Newcastle', 'Margate', 'Westerham', 'Eltham', 'Gretna', 'Cheapside', 'Hunsford', 'Bath', 'Oxford',
          'Cambridge', 'Hampshire', 'Staffordshire', 'Northumberland']
PEOPLE = ['Elizabeth', 'Jane', 'Lydia', 'Kitty', 'Mary', 'Charlotte', 'Maria', 'Georgiana', 'Caroline',
          'Louisa', 'Catherine', 'Anne', 'Fitzwilliam', 'Charles', 'George', 'William', 'Edward', 'Lizzy',
          'Darcy', 'Bingley', 'Bennet', 'Wickham', 'Collins', 'Lucas', 'Gardiner', 'Phillips', 'Hurst',
          'Forster', 'Denny', 'Jenkinson', 'Long', 'Harrington', 'Pratt', 'Chamberlayne', 'Reynolds',
          'Younge', 'Watson', 'Hill', 'Nicholls', 'Robinson', 'Metcalf', 'Carter', 'Goulding', 'King', 'Pope',
          'Webb', 'Grantley', 'Bourgh']
places = [p for p in PLACES if p in flat]
people = [p for p in PEOPLE if p in flat]
print('places', len(places), 'people', len(people))

data = {'austen': {'places': places, 'people': people, 'quotes': aph[:900], 'opening': sents[0] if sents else ''}}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/build_data.py - do not edit by hand. (The roster is src/game/roster.js.)\n')
    f.write('window.PA_DATA = ')
    json.dump(data, f, separators=(',', ':'), ensure_ascii=False)
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT) // 1024, 'KB')
