#!/usr/bin/env python3
"""
The game's font: art/font/ (Bitmap8, an original 8-bit font) -> src/gen/font.js

Reads the light (white) sheet, bitmap_font_light.png, and its metrics, bitmap_font.json: ASCII 32-126 and ten
extras (codes 128-137) in 8x8 cells, glyphs 5x7 (descenders use the 8th row), each with its own advance.
The game tints the white glyphs to any colour.

What this adds on top of the font as supplied:
  * Unicode for the extras, so the game's text can use them: > v < ^ as the menu cursor and arrows, and the
    heart, star, note, ellipsis, times and degree signs.
  * Tabular digits: every digit advances 6px (the 1 is centred), so numbers line up in columns.
  * A figure space (U+2007, 6px, blank) for padding numbers to a width.
  * A few glyphs the game needs that the font doesn't have, made from its own: e-acute (and a few graves and
    circumflexes) from e, a and i,
    a pound sign, a hollow cursor from the solid one, and a bullet.
Other characters the game used to draw map to the nearest the font has (DERIVED and ALIAS below).

usage: python3 tools/build_font.py
"""
import os, json
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'font')
OUT = os.path.join(ROOT, 'src', 'gen', 'font.js')

EXTRAS = {128: '▶', 129: '▼', 130: '◀', 131: '▲', 132: '♥', 133: '★', 134: '♪', 135: '…', 136: '×', 137: '°'}
# characters the game writes that are drawn with another glyph
ALIAS = {'→': '▶', '←': '◀', '↑': '▲', '↓': '▼', '—': '-', '–': '-', '’': "'", '‘': "'", '“': '"', '”': '"',
         'É': 'E', 'È': 'E', 'Ê': 'E', 'À': 'A', 'Â': 'A', 'Ì': 'I'}  # capitals drop their accents, as signwriters do

meta = json.load(open(os.path.join(ART, 'bitmap_font.json')))
sheet = np.array(Image.open(os.path.join(ART, 'bitmap_font_light.png')).convert('RGBA'))[..., 3] > 0
if meta.get('cell_size') != 8:
    raise SystemExit('expected 8x8 cells')

glyphs = {}  # char -> {'rows': 8 ints (bit 7 = leftmost column), 'a': advance}


def rows_of(mask):
    return [int(''.join('1' if v else '0' for v in r), 2) for r in mask]


for g in meta['glyphs']:
    code = g['code']
    ch = EXTRAS.get(code) if code >= 128 else chr(code)
    if ch is None:
        continue
    x, y, w, h = g['glyph']
    cx, cy = g['cell'][0], g['cell'][1]
    cell = sheet[cy:cy + 8, cx:cx + 8]
    # the glyph starts (x - cx) columns into its cell; shift it to column 0 so the advance is all it needs
    off = x - cx
    m = np.zeros((8, 8), bool)
    m[:, :8 - off] = cell[:, off:]
    glyphs[ch] = {'m': m, 'w': w, 'a': g['xadvance']}

# tabular digits: 6px each, narrow ones centred
for d in '0123456789':
    gl = glyphs[d]
    if gl['a'] < 6:
        shift = (5 - gl['w']) // 2
        gl['m'] = np.roll(gl['m'], shift, axis=1)
        gl['a'] = 6
glyphs[' '] = {'m': np.zeros((8, 8), bool), 'w': 0, 'a': 6}  # figure space

# derived glyphs
e = glyphs['e']['m'].copy()
e[0, 3] = e[1, 2] = True                         # an acute accent above the e
glyphs['é'] = {'m': e, 'w': 5, 'a': 6}
# grave and circumflex accents, on the same two rows as the acute (a, e and a dotless i)
for base, ch, marks in [('a', 'à', [(0, 1), (1, 2)]), ('e', 'è', [(0, 1), (1, 2)]), ('a', 'â', [(0, 2), (1, 1), (1, 3)]),
                        ('e', 'ê', [(0, 2), (1, 1), (1, 3)]), ('i', 'ì', [(0, 0), (1, 1)])]:
    m = glyphs[base]['m'].copy()
    m[0:2, :] = False                            # the i's dot makes way
    for r, c in marks:
        m[r, c] = True
    glyphs[ch] = {'m': m, 'w': glyphs[base]['w'], 'a': glyphs[base]['a']}
top = int(np.argmax(glyphs['P']['m'].any(axis=1)))  # the pound sign, on the capitals' rows
pound = np.zeros((8, 8), bool)
for j, row in enumerate(['..XX.', '.X..X', '.X...', 'XXXX.', '.X...', '.X...', 'XXXXX']):
    for i, ch in enumerate(row):
        pound[top + j, i] = ch == 'X'
glyphs['£'] = {'m': pound, 'w': 5, 'a': 6}
solid = glyphs['▶']['m']
pad = np.pad(solid, 1)
inner = pad[1:-1, 1:-1] & pad[:-2, 1:-1] & pad[2:, 1:-1] & pad[1:-1, :-2] & pad[1:-1, 2:]
glyphs['▷'] = {'m': solid & ~inner, 'w': glyphs['▶']['w'], 'a': glyphs['▶']['a']}
dot = np.zeros((8, 8), bool)
dot[3:5, 1:3] = True
glyphs['•'] = {'m': dot, 'w': 3, 'a': 4}

data = {
    'name': 'Bitmap8', 'cell': 8, 'lineHeight': meta.get('line_height', 10), 'baseline': meta.get('baseline', 7),
    'glyphs': {ch: [rows_of(g['m']), g['a']] for ch, g in glyphs.items()},
    'alias': ALIAS,
}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_font.py from art/font/ (Bitmap8, an original font) - do not edit.\n')
    f.write('// glyphs: char -> [8 rows of bits (128 = leftmost column), advance in px]\n')
    f.write('window.PA_FONT = ')
    json.dump(data, f, separators=(',', ':'), ensure_ascii=False)
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes,', len(glyphs), 'glyphs')
