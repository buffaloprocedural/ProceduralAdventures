#!/usr/bin/env python3
"""
Interior tileset: art/interior/ -> src/gen/interior_tiles.js

Reads the pixels (with their transparency) from interior_tileset.svg, the source of record, and checks
them against interior_tileset_preview_3x.png wherever the SVG is opaque. Names come from
interior_tileset_manifest.json; every 16x16 cell gets one:
  single tiles      their own name                  floor_wood_light, doorway, globe ...
  bigger pieces     <name>_<x><y>                   bookshelf_1x2_00 / bookshelf_1x2_01, rug_red_3x3_00 .. _22
Pieces lists each bigger piece's size, so src/game/furnish.js can place it by name; layers says which
cells are opaque base tiles (floors, walls, stairs) and which are objects drawn over them.
Original pixel art made for Procedural Adventures - see art/interior/CREDITS.txt.
"""
import io, os, sys, json, base64
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sprite_sheet import load_sheet  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'interior')
OUT = os.path.join(ROOT, 'src', 'gen', 'interior_tiles.js')

man = json.load(open(os.path.join(ART, 'interior_tileset_manifest.json')))
T, COLS, ROWS = man['tile_size'], man['columns'], man['rows']
px = load_sheet(os.path.join(ART, 'interior_tileset.svg'))
if px.shape[:2] != (ROWS * T, COLS * T):
    raise SystemExit('interior_tileset.svg is %dx%d, expected %dx%d' % (px.shape[1], px.shape[0], COLS * T, ROWS * T))
big = np.array(Image.open(os.path.join(ART, 'interior_tileset_preview_3x.png')).convert('RGBA'))
k = big.shape[0] // (ROWS * T)
prev = big[::k, ::k]
opaque = px[..., 3] == 255
if prev.shape[:2] != px.shape[:2] or (px[..., :3] != prev[..., :3])[opaque].any():
    raise SystemExit('the SVG and the 3x preview disagree - which one changed?')
if ((px[..., 3] > 0) & (px[..., 3] < 255)).any():
    raise SystemExit('semi-transparent pixels in the SVG; the game expects pixel art (opaque or clear)')

names, pieces, layers = {}, {}, {}
def add(name, x, y, layer):
    if name in names:
        raise SystemExit('duplicate tile name ' + name)
    names[name] = y * COLS + x
    layers[name] = layer
for it in man['items']:
    x, y, w, h, layer = it['x'], it['y'], it['w'], it['h'], it.get('layer', 'base')
    if w == 1 and h == 1:
        add(it['name'], x, y, layer)
        continue
    pieces[it['name']] = [w, h]
    for dy in range(h):
        for dx in range(w):
            add('%s_%d%d' % (it['name'], dx, dy), x + dx, y + dy, layer)
for n, t in names.items():  # a base tile must cover its cell
    cell = px[(t // COLS) * T:(t // COLS + 1) * T, (t % COLS) * T:(t % COLS + 1) * T]
    if layers[n] == 'base' and (cell[..., 3] < 255).any():
        raise SystemExit('base tile %s has transparent pixels' % n)

buf = io.BytesIO()
Image.fromarray(px, 'RGBA').save(buf, 'PNG', optimize=True)
data = {'png': 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode(), 'cell': T, 'cols': COLS,
        'names': names, 'pieces': pieces, 'objects': sorted(names[n] for n in names if layers[n] == 'object')}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/build_interior_tiles.py from art/interior/ - do not edit.\n')
    f.write('// Original interior tileset made for Procedural Adventures - see art/interior/CREDITS.txt\n')
    f.write('window.PA_INTERIOR_TILES = ')
    json.dump(data, f, separators=(',', ':'))
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes,', len(names), 'named cells,', len(pieces), 'bigger pieces,',
      len(data['objects']), 'object cells')
