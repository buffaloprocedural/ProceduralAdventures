#!/usr/bin/env python3
"""
Protagonist sprites: art/protagonist/hero_masc_1..6.svg + hero_femme_1..6.svg -> src/gen/hero.js

Original pixel art made for Procedural Adventures (see art/protagonist/CREDITS.txt and VARIANTS_README.txt).
Each sheet (PNG, or a pixel-grid SVG - see tools/sprite_sheet.py) is 3x4 frames of 16x16:
rows = [down, up, left, right]; columns = [stand, step, other step].

They are packed into one atlas: row 0 = masc 1-6, row 1 = femme 1-6. After choosing BOY or GIRL the player is
given one of that row's six at random (src/main.js PA.pickLook). 'boy' and 'girl' name masc_1 and femme_1, the
looks used when none has been picked (e.g. an older saved game).
"""
import os, io, sys, json, base64
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sprite_sheet import load_sheet  # noqa: E402  (PNG or pixel-SVG; fails loudly on anything else)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'protagonist')
OUT = os.path.join(ROOT, 'src', 'gen', 'hero.js')
CELL = 16
KINDS = ('masc', 'femme')
N = 6


def find(name):
    for ext in ('.svg', '.png'):
        p = os.path.join(ART, name + ext)
        if os.path.exists(p):
            return p
    raise SystemExit('missing art/protagonist/%s.svg (or .png)' % name)


atlas = np.zeros((len(KINDS) * 4 * CELL, N * 3 * CELL, 4), np.uint8)
chars, looks = {}, {}
for r, kind in enumerate(KINDS):
    looks[kind] = []
    for i in range(1, N + 1):
        name = 'hero_%s_%d' % (kind, i)
        rgba = load_sheet(find(name))
        if rgba.shape[:2] != (4 * CELL, 3 * CELL):
            raise SystemExit('%s: a walk sheet is 48x64 (3 frames x 4 directions), got %dx%d' % (name, rgba.shape[1], rgba.shape[0]))
        if not rgba[..., 3].any():
            raise SystemExit('%s is empty' % name)
        col, row = (i - 1) * 3, r * 4
        atlas[row * CELL:(row + 4) * CELL, col * CELL:(col + 3) * CELL] = rgba
        key = '%s_%d' % (kind, i)
        chars[key] = [col, row]
        looks[kind].append(key)
chars['boy'] = chars['masc_1']
chars['girl'] = chars['femme_1']

buf = io.BytesIO()
Image.fromarray(atlas, 'RGBA').save(buf, 'PNG', optimize=True)
data = {
    'png': 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode(),
    'cell': CELL,
    'rows': {'down': 0, 'up': 1, 'left': 2, 'right': 3},
    'cols': [0, 1, 2],  # frame column for [standing, step, other step]
    # [column, row] of each character's 3x4 block, in frames
    'chars': chars,
    # the looks a player of each kind is given one of
    'looks': looks,
}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/build_hero.py from art/protagonist/hero_*.svg - do not edit.\n')
    f.write('// Original pixel art made for Procedural Adventures - see art/protagonist/CREDITS.txt\n')
    f.write('window.PA_HERO = ')
    json.dump(data, f, separators=(',', ':'))
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes,', len(KINDS) * N, 'looks')
