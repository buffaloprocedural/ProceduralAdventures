#!/usr/bin/env python3
"""
Overworld tileset: art/tiles/ -> src/gen/world_tiles.js

Reads the pixels from overworld_tileset.png, the 1x sheet and source of record (edited by hand since
October 2026), falling back to tileset_preview_3x.png (an exact 3x copy of the original overworld_tileset.svg);
the names come from tileset_manifest.json. Run it with --preview to rewrite the 3x preview from the 1x sheet. Every 16x16 cell gets a name:
  single tiles      their own name                         grass, sign_wood, cave_ladder ...
  edge sets         <set>_<part>                           path_nw, water_center, sand_inner_se ...
  bigger pieces     <name without _WxH>_<x><y>             tree_round_00 .. tree_round_11, roof_red_00 .. roof_red_31
Animations become {first frame index: [frame indices]}.
Original pixel art made for Procedural Adventures - see art/tiles/CREDITS.txt.
"""
import io, os, re, sys, json, base64
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'tiles')
OUT = os.path.join(ROOT, 'src', 'gen', 'world_tiles.js')

man = json.load(open(os.path.join(ART, 'tileset_manifest.json')))
T, COLS, ROWS = man['tile_size'], man['columns'], man['rows']
ONE = os.path.join(ART, 'overworld_tileset.png')
if os.path.exists(ONE):
    one = Image.open(ONE).convert('RGBA')
    if one.size != (COLS * T, ROWS * T):
        raise SystemExit('overworld_tileset.png is %dx%d, expected %dx%d' % (one.size[0], one.size[1], COLS * T, ROWS * T))
    a = np.array(one)
    a[a[..., 3] < 128] = 0          # semi-transparent pixels: clear or solid, as the game draws them
    a[a[..., 3] >= 128, 3] = 255
    if '--preview' in sys.argv:
        Image.fromarray(a, 'RGBA').resize((COLS * T * 3, ROWS * T * 3), Image.NEAREST).save(os.path.join(ART, 'tileset_preview_3x.png'))
    big = a
else:
    big = np.array(Image.open(os.path.join(ART, 'tileset_preview_3x.png')).convert('RGBA'))
k = big.shape[0] // (ROWS * T)
if big.shape != (ROWS * T * k, COLS * T * k, 4):
    raise SystemExit('preview is %dx%d, expected %dx of %dx%d' % (big.shape[1], big.shape[0], k, COLS * T, ROWS * T))
blocks = big.reshape(ROWS * T, k, COLS * T, k, 4)
if not (blocks == blocks[:, :1, :, :1]).all():
    raise SystemExit('preview is not an exact %dx enlargement' % k)
px = big[::k, ::k].copy()

names = {}
def add(name, x, y):
    if name in names:
        raise SystemExit('duplicate tile name ' + name)
    names[name] = y * COLS + x
for it in man['items']:
    x, y, w, h = it['x'], it['y'], it['w'], it['h']
    if 'layout' in it:
        prefix = it['name'].split('_edges')[0]
        for ry, row in enumerate(it['layout']):
            for rx, part in enumerate(row):
                if part:
                    add(prefix + '_' + part, x + rx, y + ry)
    elif w == 1 and h == 1:
        add(it['name'], x, y)
    else:
        base = re.sub(r'_\d+x\d+$', '', it['name'])
        for dy in range(h):
            for dx in range(w):
                add('%s_%d%d' % (base, dx, dy), x + dx, y + dy)
anim = {}
for key, frames in man['animation'].items():
    if key == 'tall_grass_step':  # a one-off rustle when stepped in, not a loop
        continue
    idx = [names[f] for f in frames]
    anim[str(idx[0])] = idx

buf = io.BytesIO()
Image.fromarray(px, 'RGBA').save(buf, 'PNG', optimize=True)
data = {'png': 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode(), 'cell': T, 'cols': COLS,
        'names': names, 'anim': anim}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/build_world_tiles.py from art/tiles/ - do not edit.\n')
    f.write('// Original overworld tileset made for Procedural Adventures - see art/tiles/CREDITS.txt\n')
    f.write('window.PA_WORLD_TILES = ')
    json.dump(data, f, separators=(',', ':'))
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes,', len(names), 'named cells,', len(anim), 'animations')
