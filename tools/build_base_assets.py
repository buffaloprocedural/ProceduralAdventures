#!/usr/bin/env python3
"""
Writes src/gen/assets.js from the project's own sources:
  art/tiles/base_tiles.json   the map-tile vocabulary (names -> slots) and the building stamps (size, door)
  a blank tile atlas          every slot white except 'black'; the game draws its tiles from art/tiles and
                              art/interior (tools/build_world_tiles.py, tools/build_interior_tiles.py)
Then run tools/build_objects.py (objects and emote bubbles) and tools/build_fx.py (battle effects), which write
their parts into the same file.

usage: python3 tools/build_base_assets.py && python3 tools/build_objects.py && python3 tools/build_fx.py
"""
import base64
import io
import json
import os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'gen', 'assets.js')
BASE = json.load(open(os.path.join(ROOT, 'art', 'tiles', 'base_tiles.json'), encoding='utf-8'))


def png(arr):
    buf = io.BytesIO()
    Image.fromarray(arr, 'RGBA').save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


cols, rows = 16, (BASE['tileCount'] + 15) // 16
atlas = np.full((rows * 16, cols * 16, 4), 255, np.uint8)  # white, opaque
b = BASE['tileNames']['black']
atlas[(b // cols) * 16:(b // cols) * 16 + 16, (b % cols) * 16:(b % cols) * 16 + 16, :3] = 0

old = {}
if os.path.exists(OUT):  # keep what tools/build_objects.py and tools/build_fx.py wrote last
    old = json.loads(open(OUT, encoding='utf-8').read().split('window.PA_ASSETS = ', 1)[1].rstrip().rstrip(';'))
data = {
    'tiles': png(atlas), 'tileCount': BASE['tileCount'], 'tileNames': BASE['tileNames'], 'retiredTiles': BASE['retiredTiles'],
    'stamps': BASE['stamps'],
    'chars': old.get('chars') or png(np.zeros((32, 160, 4), np.uint8)), 'charRows': 2,
    **{k: old[k] for k in ('fx', 'fxTiles') if k in old},
}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_base_assets.py, tools/build_objects.py and tools/build_fx.py - do not edit by hand.\n')
    f.write('window.PA_ASSETS = ')
    json.dump(data, f, separators=(',', ':'), ensure_ascii=False)
    f.write(';\n')
print('wrote', os.path.relpath(OUT, ROOT), '-', BASE['tileCount'], 'tile slots,', len(BASE['stamps']), 'stamps' + ('' if 'fx' in data else ' (now run tools/build_fx.py)'))
