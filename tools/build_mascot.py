#!/usr/bin/env python3
"""
The mascot, GULLIVER the cool seagull: art/mascot/ -> src/gen/mascot.js

  gulliver_overworld.svg   3x4 walk sheet (same layout as every other character sheet)
  gulliver_battle.svg      his battle set, 80x32: front 32x32 at (0,0), back 32x32 at (32,0),
                           party-menu icon frames 16x16 at (64,0) and (64,16) - checked here, built into the
                           creature atlas by tools/build_creatures.py (he is the roster's GULLET)

Original pixel art made for Procedural Adventures - see art/mascot/CREDITS.txt.
"""
import io, os, sys, json, base64
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sprite_sheet import load_sheet  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'mascot')
OUT = os.path.join(ROOT, 'src', 'gen', 'mascot.js')


def png_uri(rgba):
    buf = io.BytesIO()
    Image.fromarray(rgba, 'RGBA').save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


walk = load_sheet(os.path.join(ART, 'gulliver_overworld.svg'))
if walk.shape[:2] != (64, 48):
    raise SystemExit('overworld sheet should be 48x64, got %dx%d' % (walk.shape[1], walk.shape[0]))
battle = load_sheet(os.path.join(ART, 'gulliver_battle.svg'))
if battle.shape[:2] != (32, 80):
    raise SystemExit('battle set should be 80x32 (front, back, two icons), got %dx%d' % (battle.shape[1], battle.shape[0]))
for name, (x, y, s) in {'front': (0, 0, 32), 'back': (32, 0, 32), 'icon 1': (64, 0, 16), 'icon 2': (64, 16, 16)}.items():
    if not battle[y:y + s, x:x + s, 3].any():
        raise SystemExit('the %s view of the battle set is empty' % name)
data = {
    'name': 'GULLIVER', 'species': 'GULLET',
    'overworld': {'png': png_uri(walk), 'cell': 16, 'rows': {'down': 0, 'up': 1, 'left': 2, 'right': 3},
                  'cols': [0, 1, 2], 'chars': {'gulliver': [0, 0]}},
}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/build_mascot.py from art/mascot/ - do not edit.\n')
    f.write('// GULLIVER, the cool seagull: original pixel art made for Procedural Adventures (art/mascot/CREDITS.txt)\n')
    f.write('window.PA_MASCOT = ')
    json.dump(data, f, separators=(',', ':'))
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes; battle set checked (', int((battle[..., 3] > 0).sum()), 'opaque pixels) - rebuild src/gen/creatures.js too')
