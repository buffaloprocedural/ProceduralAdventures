#!/usr/bin/env python3
"""
NPC sprites: art/npcs/**/NN_name.svg (or .png) -> src/gen/people.js

Original pixel art made for Procedural Adventures (see the CREDITS.txt in each art/npcs folder).
Every sheet is 48x64: 3x4 frames of 16x16, rows = [down, up, left, right],
columns = [stand, step, other step] - the same layout as the protagonist.

The sheets are packed into one atlas, five across. Each character is keyed by the
name after its number (01_rival.svg -> 'rival'); src/game/maps.js maps the game's
roles onto these names (PA.SPR). Add a sheet here and it is available as PA.SPR[name].

A folder may hold a meta.json: {"names": {key: "DISPLAY NAME"}, "reserve": true}. Names go into
PA_PEOPLE.names (PA.personName(key)); a reserve folder's characters are built and ready to use,
but the world doesn't place them yet, so tests/worldgen_test.js doesn't expect to see them.
"""
import os, io, re, sys, json, glob, base64
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sprite_sheet import load_sheet  # noqa: E402  (PNG or pixel-SVG; fails loudly on anything else)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'art', 'npcs')
OUT = os.path.join(ROOT, 'src', 'gen', 'people.js')
CELL, SW, SH, ACROSS = 16, 48, 64, 5

files = {}
paths = glob.glob(os.path.join(SRC, '**', '*.svg'), recursive=True) + glob.glob(os.path.join(SRC, '**', '*.png'), recursive=True)
for f in sorted(paths, key=lambda p: (os.path.dirname(p), os.path.basename(p))):
    m = re.fullmatch(r'\d+_([a-z0-9_]+)\.(svg|png)', os.path.basename(f))
    if not m:
        raise SystemExit('unexpected file name %s (want NN_name.svg)' % f)
    if m.group(1) in files:
        raise SystemExit('two sheets for %r: %s and %s' % (m.group(1), files[m.group(1)], f))
    files[m.group(1)] = f
if not files:
    raise SystemExit('no sheets in ' + SRC)
display, reserve = {}, []
for meta_path in sorted(glob.glob(os.path.join(SRC, '**', 'meta.json'), recursive=True)):
    meta = json.load(open(meta_path))
    folder = os.path.dirname(meta_path)
    here = [k for k, f in files.items() if os.path.dirname(f) == folder]
    for k, v in meta.get('names', {}).items():
        if k not in here:
            raise SystemExit('%s names %r, but there is no %s/NN_%s sheet' % (meta_path, k, folder, k))
        display[k] = v
    if meta.get('reserve'):
        reserve += here

names = list(files)
down = (len(names) + ACROSS - 1) // ACROSS
atlas = np.zeros((down * SH, ACROSS * SW, 4), np.uint8)
chars = {}
for i, name in enumerate(names):
    sheet = load_sheet(files[name])
    if sheet.shape[:2] != (SH, SW):
        raise SystemExit('%s is %dx%d, expected %dx%d' % (files[name], sheet.shape[1], sheet.shape[0], SW, SH))
    col, row = i % ACROSS, i // ACROSS
    atlas[row * SH:(row + 1) * SH, col * SW:(col + 1) * SW] = sheet
    chars[name] = [col * 3, row * 4]  # in frames

buf = io.BytesIO()
Image.fromarray(atlas, 'RGBA').save(buf, 'PNG', optimize=True)
data = {
    'png': 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode(),
    'cell': CELL,
    'rows': {'down': 0, 'up': 1, 'left': 2, 'right': 3},
    'cols': [0, 1, 2],  # frame column for [standing, step, other step]
    'chars': chars,     # name -> [column, row] of its 3x4 block, in frames
    'names': display,   # name -> in-game display name, where a meta.json gives one
    'reserve': reserve, # built and ready, but not placed in the world yet
}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/build_people.py from art/npcs/ - do not edit.\n')
    f.write('// Original pixel art made for Procedural Adventures - see art/npcs/CREDITS.txt\n')
    f.write('window.PA_PEOPLE = ')
    json.dump(data, f, separators=(',', ':'))
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes,', len(names), 'characters (%d in reserve):' % len(reserve), ' '.join(names))
